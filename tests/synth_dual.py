"""Synthetic two-colour (4-tool) Co Print-structured slice for tests.

Two identical two-colour boxes side by side: left box colours on T0/T2, right box
on T1/T3, right = left translated by (dx, 0). Every 10 layers the two colours
swap halves, so colour boundaries also occur vertically. The tool-change
machinery mirrors the real export (CP TOOLCHANGE blocks, prime tower moves,
standby/print temperatures) so the strict reader is exercised.
"""
from __future__ import annotations

import math

from synth import CONFIG

DUAL_CFG = CONFIG.replace("; CONFIG_BLOCK_END", """; filament_colour = #0000FF;#FF0000;#00FF00;#FFFF00
; preheat_time = 17
; standby_temperature_delta = -80
; wipe_distance = 2,2,2,2
; enable_prime_tower = 1
; wipe_tower_x = 30
; wipe_tower_y = 230
; CONFIG_BLOCK_END""")


def region(tool, L, x0, y0, w, h, dx, grow=False):
    if grow:
        # colour 1 (T0/T1) grows into colour 2 every layer: colour 1 is printed on colour 2, never the reverse
        f = min(0.8, 0.3 + 0.02 * max(0, L - 5))     # starts growing above the independent layers
        c1 = tool in (0, 1)
        gap = 0.42                                    # neighbouring perimeters one line apart, as a slicer places them
        rx = x0 + (0.0 if c1 else f * w + gap) + (dx if tool in (1, 3) else 0.0)
        return rx, y0, (f * w if c1 else (1.0 - f) * w - gap), h
    half = w / 2.0
    colour1_left = (L - 1) // 10 % 2 == 0
    left_half = (tool in (0, 1)) == colour1_left
    rx = x0 + (0.0 if left_half else half) + (dx if tool in (1, 3) else 0.0)
    return rx, y0, half, h


def dual_gcode(size=(24.0, 14.0), layers=12, center=(110.0, 150.0), dx=80.0, temp=215, bed=55,
               differ_layer=None, right_patch=False, renumber=False, grow=False):
    """renumber=True writes the slice with left model T0/T1 and right model T2/T3
    (slice tool -> physical head: T0->T0, T1->T2, T2->T1, T3->T3)."""
    w, h = size
    x0, y0 = center[0] - w / 2, center[1] - h / 2
    ea = math.pi * (1.75 / 2) ** 2

    def e(len_, wd=0.45):
        return (wd - 0.2 * (1 - math.pi / 4)) * 0.2 * len_ / ea
    out = ["; HEADER_BLOCK_START", "; generated by CoPrintSlicer 1.0.0 on 2026-11-14 at 10:00:00",
           "; total layer number: %d" % layers, "; filament: 1,2,3,4", "; HEADER_BLOCK_END", "", "; EXECUTABLE_BLOCK_START",
           ";TYPE:Custom",
           "start_print EXTRUDER=0 EXTRUDER_TEMP=%d PURGE_LINE='false' BED_TEMP=%d EXT0=true EXT1=true EXT2=true EXT3=true "
           "EXT0_TEMP=%d EXT1_TEMP=%d EXT2_TEMP=%d EXT3_TEMP=%d" % (temp, bed, temp, temp, temp, temp),
           "G90", "G21", "M83", "SET_PRESSURE_ADVANCE ADVANCE=0.04", "T0", "G1 E-.4 F3000"]
    cur = 0
    for L in range(1, layers + 1):
        z = round(0.2 * L, 3)
        out += [";LAYER_CHANGE", ";Z:%g" % z, ";HEIGHT:0.2", ";LAYER:%d" % L, "SET_PRINT_STATS_INFO CURRENT_LAYER=%d" % L]
        if L == 2:
            out.append("M106 S255")
        for t in (0, 1, 2, 3):
            if t != cur:
                out += [";TYPE:Prime tower", ";WIDTH:0.5", "; CP TOOLCHANGE START", "M220 S100", "G4 S0", "G1 E-3.6 F3000",
                        "M104 S140 T%d ; set nozzle temperature ;cooldown" % cur, "G1 Z%.3f F18000" % (z + 0.4),
                        'RESPOND MSG="TC NEXT=%d XA=30 YA=230"' % t, "T%d X=30 Y=230" % t, "M109 S%d T%d" % (temp, t),
                        "SET_PRESSURE_ADVANCE ADVANCE=0.04", "G1 X30.0 Y230.0", "G1 Z%.3f" % z, "G1 E4 F3000",
                        "G1 X50.0 E0.6 F1980", "G1 Y231.0 E0.03", "G1 X30.0 E0.6", "G1 E-.4 F3000", "G4 S0", "G92 E0",
                        "; CP TOOLCHANGE END"]
                cur = t
            hd = {0: 0, 1: 2, 2: 1, 3: 3}[t] if renumber else t
            rx, ry, rw, rh = region(hd, L, x0, y0, w, h, dx, grow)
            if right_patch and hd == 1 and L == differ_layer:
                rw *= 0.6                                  # the right model's colour-1 region differs on this layer
            out.append("; printing object box id:0 copy 0")
            out += ["G1 X%.3f Y%.3f Z%.3f F18000" % (rx, ry, z + 0.4), "G1 Z%.3f" % z, "G1 E.4 F3000",
                    "SET_VELOCITY_LIMIT ACCEL=%d ACCEL_TO_DECEL=%d" % ((500, 250) if L == 1 else (3000, 1500)),
                    ";TYPE:Outer wall", ";WIDTH:0.45", "G1 F3000"]
            pts = [(rx, ry), (rx + rw, ry), (rx + rw, ry + rh), (rx, ry + rh), (rx, ry)]
            for (ax, ay), (bx, by) in zip(pts, pts[1:]):
                out.append("G1 X%.3f Y%.3f E%.5f" % (bx, by, e(math.hypot(bx - ax, by - ay))))
            out += ["G1 E-.4 F3000", "G1 X%.3f Y%.3f Z%.3f F18000" % (rx + 1, ry + 1, z + 0.4), "G1 Z%.3f" % z, "G1 E.4 F3000",
                    ";TYPE:Sparse infill", ";WIDTH:0.42", "G1 F6000"]
            yy, px, k = ry + 1, rx + 1, 0
            while yy <= ry + rh - 1 + 1e-9:
                nx = rx + rw - 1 if k % 2 == 0 else rx + 1
                out.append("G1 X%.3f Y%.3f E%.5f" % (nx, yy, e(abs(nx - px), 0.42)))
                px = nx
                if yy + 0.42 <= ry + rh - 1 + 1e-9:
                    out.append("G1 X%.3f Y%.3f E%.5f" % (px, yy + 0.42, e(0.42, 0.42)))
                yy += 0.42
                k += 1
            out.append("; stop printing object box id:0 copy 0")
    out += ["G1 E-.4 F3000", "M106 S0", ";TYPE:Custom", "end_print", "; EXECUTABLE_BLOCK_END", ""]
    return "\n".join(out) + "\n" + DUAL_CFG


def write(path, **kw):
    with open(path, "w") as f:
        f.write(dual_gcode(**kw))
    return path
