"""Synthetic Co Print Slicer-dialect inputs for tests.

Writes a small, valid single-object slice (a hollow box with perimeters,
infill lines, retractions, wipes and z-hops) in the same structure as a Co
Print Slicer export. Used to prove regeneration for a different model and to
build negative cases without touching private fixtures.
"""
from __future__ import annotations

import math

CONFIG = """; CONFIG_BLOCK_START
; layer_height = 0.2
; gcode_flavor = klipper
; use_relative_e_distances = 1
; use_firmware_retraction = 0
; enable_arc_fitting = 0
; extruder_offset = 0x0,0x0,0x0,0x0
; retraction_length = 0.4,0.4,0.4,0.4
; retraction_speed = 50,50,50,50
; retract_length_toolchange = 4,4,4,4
; travel_speed = 300
; travel_acceleration = 7000
; initial_layer_travel_acceleration = 1000
; default_acceleration = 7000
; nozzle_diameter = 0.4,0.4,0.4,0.4
; filament_diameter = 1.75,1.75,1.75,1.75
; initial_layer_print_height = 0.2
; z_hop = 0.4,0.4,0.4,0.4
; printable_area = 0x0,300x0,300x300,0x300
; deretraction_speed = 50,50,50,50
; CONFIG_BLOCK_END
"""


def box_gcode(size=(20.0, 14.0), layers=12, center=(150.0, 150.0), extra_lines=(), layer_extra=None, temp=215, bed=55):
    w, h = size
    cx, cy = center
    x0, y0, x1, y1 = cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2
    out = ["; HEADER_BLOCK_START", "; generated by CoPrintSlicer 1.0.0 on 2026-11-14 at 10:00:00",
           "; total layer number: %d" % layers, "; HEADER_BLOCK_END", "", "; EXECUTABLE_BLOCK_START",
           ";TYPE:Custom",
           "start_print EXTRUDER=0 EXTRUDER_TEMP=%d PURGE_LINE='false' BED_TEMP=%d EXT0=true EXT1=false EXT2=false EXT3=false "
           "EXT0_TEMP=%d EXT1_TEMP=%d EXT2_TEMP=%d EXT3_TEMP=%d" % (temp, bed, temp, temp, temp, temp),
           "G90", "G21", "M83 ; use relative distances for extrusion", "SET_PRESSURE_ADVANCE ADVANCE=0.04", "T0"]
    out += list(extra_lines)
    ea = math.pi * (1.75 / 2) ** 2
    for L in range(1, layers + 1):
        z = round(0.2 * L, 3)
        out += [";LAYER_CHANGE", ";Z:%g" % z, ";HEIGHT:0.2"]
        if L == 1:
            out.append("G1 E-.4 F3000")
        else:
            out += [";WIPE_START", "G1 F6000", "G1 X%.3f Y%.3f E-.2" % (x0 + 1.0, y0), "G1 X%.3f Y%.3f E-.2" % (x0 + 2.0, y0), ";WIPE_END"]
        out += [";LAYER:%d" % L, "SET_PRINT_STATS_INFO CURRENT_LAYER=%d" % L]
        if L == 2:
            out.append("M106 S255")
        out.append("; printing object box.stl id:1 copy 0")
        out += ["G1 X%.3f Y%.3f Z%.3f F18000" % (x0, y0, z + 0.4), "G1 Z%.3f" % z, "G1 E.4 F3000",
                "SET_VELOCITY_LIMIT ACCEL=%d ACCEL_TO_DECEL=%d" % ((500, 250) if L == 1 else (3000, 1500)),
                ";TYPE:Outer wall", ";WIDTH:0.45", "G1 F3000"]
        if layer_extra:
            out += list(layer_extra(L))
        wdt = 0.45

        def e(len_):
            return (wdt - 0.2 * (1 - math.pi / 4)) * 0.2 * len_ / ea
        for (ax, ay), (bx, by) in [((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))]:
            out.append("G1 X%.3f Y%.3f E%.5f" % (bx, by, e(math.hypot(bx - ax, by - ay))))
        # retract, hop, travel inside, infill zig-zag
        out += ["G1 E-.4 F3000", "G1 X%.3f Y%.3f Z%.3f F18000" % (x0 + 1, y0 + 1, z + 0.4), "G1 Z%.3f" % z, "G1 E.4 F3000",
                ";TYPE:Sparse infill", ";WIDTH:0.42", "G1 F6000"]
        wdt = 0.42
        yy = y0 + 1
        step = 2.0
        dirn = 1
        px, py = x0 + 1, y0 + 1
        while yy <= y1 - 1 + 1e-9:
            nx = x1 - 1 if dirn > 0 else x0 + 1
            out.append("G1 X%.3f Y%.3f E%.5f" % (nx, yy, e(abs(nx - px))))
            px = nx
            if yy + step <= y1 - 1 + 1e-9:
                out.append("G1 X%.3f Y%.3f E%.5f" % (px, yy + step, e(step)))
            yy += step
            dirn = -dirn
        out.append("; stop printing object box.stl id:1 copy 0")
    out += ["G1 E-.4 F3000", "M106 S0", ";TYPE:Custom", "end_print", "; EXECUTABLE_BLOCK_END", ""]
    return "\n".join(out) + "\n" + CONFIG


def write(path, **kw):
    with open(path, "w") as f:
        f.write(box_gcode(**kw))
    return path
